package rohin.gameengine.commands;

import rohin.gameengine.ICommand;
import rohin.gameengine.engines.EngineMenu;
import rohin.gameengine.application.Constants;
import rohin.gameengine.systems.SystemMenuManager;

public class CommandMenuBack implements ICommand
{
    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    // Fields
    //
    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    private EngineMenu engine;


    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    // Constructors
    //
    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    // ----------------------------------------------------------------------------------------------------------------
    // Constructor 1
    // ----------------------------------------------------------------------------------------------------------------

    public CommandMenuBack ( EngineMenu engine )
    {
        this.engine = engine;
    }


    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    //
    // Methods
    //
    // ////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    // ----------------------------------------------------------------------------------------------------------------
    // Execute the command.
    // ----------------------------------------------------------------------------------------------------------------

    @ Override
    public void execute ()
    {
        SystemMenuManager manager = (SystemMenuManager) this.engine.getSystems ().get ( Constants.SYSTEM_MENU_MANAGER );
        manager.pendingAction = 4;
    }
}
